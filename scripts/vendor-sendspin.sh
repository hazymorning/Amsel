#!/usr/bin/env bash
# Copies upstream sendspin-kmp (Apache-2.0) verbatim into sendspin/: never edit it there, run this again.
# Usage: vendor-sendspin.sh [<ref> [<dest>]], ref a full 40-char commit SHA or a tag, PINNED_REF by default;
# SENDSPIN_UPSTREAM overrides the repository. sendspin/build.gradle.kts is Amsel's and never overwritten.
set -euo pipefail

PINNED_REF="d4a7256c3b6a8c8ef3d30f986d4ac90e4e9c86bc"
UPSTREAM="${SENDSPIN_UPSTREAM:-https://github.com/music-assistant/mobile-app.git}"
MODULE_DIR="sendspin-kmp"
SOURCE_SETS=(commonMain androidMain commonTest androidHostTest)
MODULE_FILES=(consumer-rules.pro README.md CHANGELOG.md)
LEGAL_FILES=(LICENSE NOTICE NOTICE.md NOTICE.txt)

repo_root="$(cd "$(dirname "$0")/.." && pwd)"
ref="${1:-$PINNED_REF}"
dest="${2:-$repo_root/sendspin}"

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

echo "Fetching $ref from $UPSTREAM"
git -C "$work" init -q
git -C "$work" remote add origin "$UPSTREAM"
git -C "$work" config advice.detachedHead false
git -C "$work" fetch -q --depth 1 --filter=blob:none origin "$ref" 2>/dev/null ||
    git -C "$work" fetch -q --depth 1 origin "$ref"
git -C "$work" sparse-checkout set --no-cone "/$MODULE_DIR/" "/gradle/libs.versions.toml" \
    "/gradle.properties" "${LEGAL_FILES[@]/#//}"
git -C "$work" checkout -q FETCH_HEAD

commit="$(git -C "$work" rev-parse 'HEAD^{commit}')"
if [[ "$ref" =~ ^[0-9a-f]{7,40}$ && "$commit" != "$ref"* ]]; then
    echo "Fetched commit $commit does not match $ref" >&2
    exit 1
fi
commit_date="$(git -C "$work" log -1 --format=%cI HEAD)"
commit_subject="$(git -C "$work" log -1 --format=%s HEAD)"
module="$work/$MODULE_DIR"
[[ -d "$module/src/commonMain" ]] || { echo "No $MODULE_DIR/src/commonMain at $commit" >&2; exit 1; }
[[ -f "$work/LICENSE" ]] || { echo "No LICENSE at $commit; refusing to vendor" >&2; exit 1; }

for dir in "$module"/src/*/; do
    name="$(basename "$dir")"
    case " ${SOURCE_SETS[*]} iosMain iosTest " in
        *" $name "*) ;;
        *) echo "warning: upstream has an unknown source set src/$name; review before shipping" >&2 ;;
    esac
done

previous_build_sha=""
if [[ -f "$dest/VENDORED.md" ]]; then
    previous_build_sha="$(sed -n 's/^- Upstream build.gradle.kts sha256: `\(.*\)`$/\1/p' "$dest/VENDORED.md")"
fi

mkdir -p "$dest"
rm -rf "$dest/src"
for set in "${SOURCE_SETS[@]}"; do
    if [[ -d "$module/src/$set" ]]; then
        mkdir -p "$dest/src"
        cp -R "$module/src/$set" "$dest/src/$set"
    fi
done
for file in "${MODULE_FILES[@]}"; do
    rm -f "$dest/$file"
    if [[ -f "$module/$file" ]]; then cp "$module/$file" "$dest/$file"; fi
done
# A module-level licence file, if upstream adds one, replaces the repository's.
for file in "${LEGAL_FILES[@]}"; do
    rm -f "$dest/$file"
    if [[ -f "$work/$file" ]]; then cp "$work/$file" "$dest/$file"; fi
    if [[ -f "$module/$file" ]]; then cp "$module/$file" "$dest/$file"; fi
    if [[ -f "$dest/$file" ]]; then chmod 644 "$dest/$file"; fi
done

if [[ ! -f "$dest/build.gradle.kts" ]]; then
    git -C "$repo_root" show HEAD:sendspin/build.gradle.kts >"$dest/build.gradle.kts"
    echo "Wrote $dest/build.gradle.kts from the repository's"
fi

version_of() { sed -n "s/^$1 *= *\"\(.*\)\"/\1/p" "$2" | head -1; }
upstream_catalog="$work/gradle/libs.versions.toml"
build_sha="$(sha256sum "$module/build.gradle.kts" | cut -d' ' -f1)"
module_version="$(sed -n 's/^sendspinVersion=//p' "$work/gradle.properties" 2>/dev/null || true)"

{
    echo "# Vendored: Sendspin module"
    echo
    echo "Generated by \`scripts/vendor-sendspin.sh\`. Do not edit anything in this directory except"
    echo "\`build.gradle.kts\`; re-run the script with a new ref instead."
    echo
    echo "- Upstream: $UPSTREAM, directory \`$MODULE_DIR/\`"
    echo "- Requested ref: \`$ref\`"
    echo "- Commit: \`$commit\` ($commit_date, \"$commit_subject\")"
    echo "- Upstream module version (\`sendspinVersion\`): ${module_version:-unknown}"
    echo "- Licence: Apache-2.0, \`LICENSE\` copied from the upstream repository root"
    echo "- Copied: \`src/{$(IFS=,; echo "${SOURCE_SETS[*]}")}\`, ${MODULE_FILES[*]}"
    echo "- Left out: \`src/iosMain\`, \`api/\` (iOS ABI dump), \`consumer-check/\`, upstream \`build.gradle.kts\`"
    echo "- Upstream build.gradle.kts sha256: \`$build_sha\`"
    echo
    echo "Upstream dependency versions at this commit (keep \`gradle/libs.versions.toml\` in step):"
    echo
    echo "| Upstream catalog key | Version |"
    echo "| --- | --- |"
    for key in kotlin agp ktor kermit kotlinx-atomicfu kotlinx-coroutines cryptographyKotlin bouncycastle concentus; do
        echo "| \`$key\` | $(version_of "$key" "$upstream_catalog") |"
    done
} >"$dest/VENDORED.md"

echo "Vendored $commit into $dest"
if [[ -n "$previous_build_sha" && "$previous_build_sha" != "$build_sha" ]]; then
    echo "warning: upstream sendspin-kmp/build.gradle.kts changed since the last vendor." >&2
    echo "         Compare its dependencies with $dest/build.gradle.kts before building." >&2
fi
amsel_catalog="$repo_root/gradle/libs.versions.toml"
if [[ -f "$amsel_catalog" ]]; then
    # upstream catalog key:Amsel catalog key
    for pair in ktor:ktor kermit:kermit kotlinx-atomicfu:atomicfu cryptographyKotlin:cryptographyKotlin \
        bouncycastle:bouncycastle concentus:concentus; do
        up="$(version_of "${pair%%:*}" "$upstream_catalog")"
        ours="$(version_of "${pair##*:}" "$amsel_catalog")"
        if [[ -n "$up" && "$up" != "$ours" ]]; then
            echo "note: upstream ${pair%%:*} = $up, Amsel ${pair##*:} = ${ours:-missing}" >&2
        fi
    done
fi
