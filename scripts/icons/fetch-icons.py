#!/usr/bin/env python3
"""Fetches the Phosphor icons listed in icons.txt, writes Android vector drawables and their ink table.

Phosphor (MIT, github.com/phosphor-icons/core) at a pinned commit. A glyph's line is 1.5 dp at every
size: Phosphor draws it 24, 16 and 12 units wide on its 256 grid in the Bold, Regular and Light
cuts, which is 1.5 dp at 16, 24 and 32 dp. So each glyph comes in all three cuts (ic_<name>,
ic_<name>_bold, ic_<name>_light), and AlignedGlyph draws the cut whose line is nearest 1.5 dp at the size
it is drawn (GlyphMetrics.kt, `weighted`). Fill and Bold glyphs that icons.txt names come in that one cut.
Every cut is one filled path, one path at 24 dp; a glyph drawn smaller than 16 dp is stroked from
Phosphor's own line drawing (raw/regular) at the width it needs. Only the icons the app uses are
copied in; no icon library is added (AGENTS.md, rule 6). The licence is copied to
app/src/main/assets/licences/.

The ink table (ui/components/IconBounds.kt) holds each drawable's measured ink bounds, so glyphs line up
on keylines by their ink, not by their 24 dp box (docs/DESIGN.md, "Foundations"), and each glyph's
cuts. Run it after editing icons.txt; it needs Python 3 and fonttools (`pip install fonttools`).
"""
import pathlib
import re
import sys
import urllib.request

from fontTools.pens.boundsPen import BoundsPen
from fontTools.svgLib.path import parse_path

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "app/src/main/res/drawable"
INK = ROOT / "app/src/main/kotlin/io/github/hazymorning/amsel/ui/components/IconBounds.kt"
LICENCES = ROOT / "app/src/main/assets/licences"
COMMIT = "2b75f3ad12b420c9504ef05df8d2564a28f8500e"  # phosphor-icons/core
BASE = f"https://raw.githubusercontent.com/phosphor-icons/core/{COMMIT}"

# Phosphor's line in each cut, in units of its 256 grid.
CUTS = {"regular": 16, "bold": 24, "light": 12}
# The heavy cut: a 1.5 dp line on a 12 dp glyph (the one inside a download's ring).
HEAVY = 32

HEADER = """<?xml version="1.0" encoding="utf-8"?>
<!-- {source}. Generated by scripts/icons/fetch-icons.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:autoMirrored="{mirrored}"
    android:tint="?android:attr/colorControlNormal"
    android:viewportWidth="256"
    android:viewportHeight="256">
{paths}</vector>
"""

INK_HEADER = """package io.github.hazymorning.amsel.ui.components

import io.github.hazymorning.amsel.R

// Generated by scripts/icons/fetch-icons.py from the Phosphor outlines. Do not edit by hand.

internal val IconBoundsTable: Map<Int, GlyphBounds> by lazy {
    mapOf(
"""

CUTS_HEADER = """
internal val IconWeightsTable: Map<Int, IconWeights> by lazy {
    mapOf(
"""


def parse(line: str):
    """`name icon [fill|bold] [mirrored] [custom] [heavy] [stroke:N]` -> a dict describing the entry."""
    words = line.split()
    name, icon, flags = words[0], words[1], words[2:]
    stroke = None
    rest = set()
    for flag in flags:
        if flag.startswith("stroke:"):
            stroke = float(flag.split(":", 1)[1])
        else:
            rest.add(flag)
    unknown = rest - {"fill", "bold", "mirrored", "custom", "heavy"}
    if unknown:
        raise SystemExit(f"{name}: unknown flags {sorted(unknown)}")
    fixed = "fill" if "fill" in rest else "bold" if "bold" in rest else None
    return {
        "name": name,
        "icon": icon,
        "fixed": fixed,
        "custom": "custom" in rest,
        "heavy": "heavy" in rest,
        "stroke": stroke,
        "mirrored": "mirrored" in rest,
    }


def fetch(path: str) -> str:
    return urllib.request.urlopen(f"{BASE}/{path}", timeout=30).read().decode()


def ink(path: str):
    pen = BoundsPen(None)
    parse_path(path, pen)
    return pen.bounds


def attr(attrs: str, key: str):
    found = re.search(rf'\b{key}="([^"]+)"', attrs)
    return found.group(1) if found else None


def as_path(tag: str, attrs: str):
    """An SVG shape as path data; None for the empty frame Phosphor puts behind every glyph."""
    def num(key: str) -> str:
        return f"{float(attr(attrs, key) or 0):g}"

    def val(key: str) -> float:
        return float(attr(attrs, key) or 0)
    if tag == "path":
        return attr(attrs, "d")
    if tag == "line":
        return f"M{num('x1')},{num('y1')}L{num('x2')},{num('y2')}"
    if tag in ("polyline", "polygon"):
        points = re.findall(r"-?[\d.]+", attr(attrs, "points"))
        pairs = [f"{points[i]},{points[i + 1]}" for i in range(0, len(points), 2)]
        return "M" + "L".join(pairs) + ("Z" if tag == "polygon" else "")
    if tag == "circle":
        cx, cy, r = val("cx"), val("cy"), val("r")
        return f"M{cx - r:g},{cy:g}A{r:g},{r:g},0,1,0,{cx + r:g},{cy:g}A{r:g},{r:g},0,1,0,{cx - r:g},{cy:g}Z"
    if tag == "ellipse":
        cx, cy, rx, ry = val("cx"), val("cy"), val("rx"), val("ry")
        return f"M{cx - rx:g},{cy:g}A{rx:g},{ry:g},0,1,0,{cx + rx:g},{cy:g}A{rx:g},{ry:g},0,1,0,{cx - rx:g},{cy:g}Z"
    if tag == "rect":
        x, y, w, h = val("x"), val("y"), val("width"), val("height")
        if w >= 256 and h >= 256:
            return None
        r = val("rx")
        if r == 0:
            return f"M{x:g},{y:g}h{w:g}v{h:g}h{-w:g}Z"
        return (
            f"M{x + r:g},{y:g}h{w - 2 * r:g}a{r:g},{r:g},0,0,1,{r:g},{r:g}v{h - 2 * r:g}a{r:g},{r:g},0,0,1,{-r:g},{r:g}"
            f"h{-(w - 2 * r):g}a{r:g},{r:g},0,0,1,{-r:g},{-r:g}v{-(h - 2 * r):g}a{r:g},{r:g},0,0,1,{r:g},{-r:g}Z"
        )
    raise SystemExit(f"unexpected <{tag}> in a line drawing")


def strokes(svg: str, width: float):
    """A line drawing as vector paths, every line [width] units wide, and its ink."""
    root = svg.split(">", 1)[0]
    # SVG fills a shape and strokes none unless the drawing or the shape says otherwise.
    fill_default, stroke_default = attr(root, "fill") or "#000", attr(root, "stroke") or "none"
    out, bounds = [], []
    for tag, attrs in re.findall(r"<(path|line|polyline|polygon|circle|ellipse|rect)\b([^>]*?)/?>", svg):
        d = as_path(tag, attrs)
        if d is None:
            continue
        fill, stroke = attr(attrs, "fill") or fill_default, attr(attrs, "stroke") or stroke_default
        filled = fill != "none"
        stroked = stroke != "none"
        lines = ["    <path"]
        if filled:
            lines.append('        android:fillColor="@android:color/white"')
        if stroked:
            lines += [
                '        android:strokeColor="@android:color/white"',
                f'        android:strokeWidth="{width:g}"',
                '        android:strokeLineCap="round"',
                '        android:strokeLineJoin="round"',
            ]
        lines.append(f'        android:pathData="{d}" />')
        out.append("\n".join(lines) + "\n")
        x0, y0, x1, y1 = ink(d)
        grow = width / 2 if stroked else 0
        bounds.append((x0 - grow, y0 - grow, x1 + grow, y1 + grow))
    box = (min(b[0] for b in bounds), min(b[1] for b in bounds), max(b[2] for b in bounds), max(b[3] for b in bounds))
    return "".join(out), box


def outline(icon: str, cut: str):
    """Phosphor's filled outline of [icon] in [cut], and its ink."""
    suffix = "" if cut == "regular" else f"-{cut}"
    svg = fetch(f"assets/{cut}/{icon}{suffix}.svg")
    paths = re.findall(r'<path d="([^"]+)"', svg)
    if len(paths) != 1:
        raise SystemExit(f"{icon}: expected one path in {icon}{suffix}, found {len(paths)}")
    return f'    <path\n        android:fillColor="@android:color/white"\n        android:pathData="{paths[0]}" />\n', ink(paths[0])


def drawables(entry):
    """Every drawable an entry writes: (suffix, source line, paths, ink box)."""
    icon = entry["icon"]
    if entry["custom"]:
        svg = (ROOT / "scripts/icons/custom" / f"{icon}.svg").read_text()
        source = f'Amsel\'s own "{icon}", drawn to Phosphor\'s spec'
        if 'stroke="none"' in svg.split(">", 1)[0] or entry["fixed"] == "fill":
            return [("", source, *strokes(svg, CUTS["regular"]))]
        return [(cut_suffix(cut), f"{source}, {cut}", *strokes(svg, width)) for cut, width in CUTS.items()]
    if entry["stroke"] is not None:
        source = f'Phosphor "{icon}", a {entry["stroke"]:g} unit line (MIT, phosphor-icons/core)'
        return [("", source, *strokes(fetch(f"raw/regular/{icon}.svg"), entry["stroke"]))]
    if entry["fixed"] is not None:
        return [("", f'Phosphor "{icon}", {entry["fixed"]} (MIT, phosphor-icons/core)', *outline(icon, entry["fixed"]))]
    made = [(cut_suffix(cut), f'Phosphor "{icon}", {cut} (MIT, phosphor-icons/core)', *outline(icon, cut)) for cut in CUTS]
    if entry["heavy"]:
        source = f'Phosphor "{icon}", a {HEAVY} unit line (MIT, phosphor-icons/core)'
        made.append(("_heavy", source, *strokes(fetch(f"raw/regular/{icon}.svg"), HEAVY)))
    return made


def cut_suffix(cut: str) -> str:
    return "" if cut == "regular" else f"_{cut}"


def cut_entry(name: str, heavy: bool) -> str:
    """One line of the cuts table, or one line for each of its parts where that is too long for ktlint."""
    parts = [f"R.drawable.ic_{name}_bold", f"R.drawable.ic_{name}_light"]
    if heavy:
        parts.append(f"R.drawable.ic_{name}_heavy")
    line = f"        R.drawable.ic_{name} to IconWeights({', '.join(parts)}),\n"
    if len(line) <= 121:
        return line
    inner = "".join(f"            {part},\n" for part in parts)
    return f"        R.drawable.ic_{name} to IconWeights(\n{inner}        ),\n"


def main() -> int:
    lines = (ROOT / "scripts/icons/icons.txt").read_text().splitlines()
    entries = [parse(l) for l in lines if l.strip() and not l.lstrip().startswith("#")]
    written, table, cuts = set(), [], []
    for entry in entries:
        name, mirrored = entry["name"], str(entry["mirrored"]).lower()
        made = drawables(entry)
        for suffix, source, paths, box in made:
            file = f"ic_{name}{suffix}.xml"
            (OUT / file).write_text(HEADER.format(source=source, paths=paths, mirrored=mirrored))
            written.add(file)
            x0, y0, x1, y1 = (round(v, 1) for v in box)
            table.append(f"        R.drawable.ic_{name}{suffix} to GlyphBounds({x0}f, {y0}f, {x1}f, {y1}f, mirrored = {mirrored}),\n")
        suffixes = {suffix for suffix, *_ in made}
        if {"_bold", "_light"} <= suffixes:
            cuts.append(cut_entry(name, "_heavy" in suffixes))
        print(f"wrote ic_{name} ({len(made)})")
    # Icons that left the list are deleted, so the folder always matches it.
    for old in OUT.glob("ic_*.xml"):
        if old.name not in written and not old.name.startswith("ic_launcher"):
            old.unlink()
            print(f"removed {old.relative_to(ROOT)}")
    INK.write_text(INK_HEADER + "".join(table) + "    )\n}\n" + CUTS_HEADER + "".join(cuts) + "    )\n}\n")
    print(f"wrote {INK.relative_to(ROOT)}")
    LICENCES.mkdir(parents=True, exist_ok=True)
    (LICENCES / "MIT-Phosphor.txt").write_bytes(urllib.request.urlopen(f"{BASE}/LICENSE", timeout=30).read())
    return 0


if __name__ == "__main__":
    sys.exit(main())
