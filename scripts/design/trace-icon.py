#!/usr/bin/env python3
"""Turns the owner's icon artwork (docs/design/icon/amsel-icon.png, 1024 px, full bleed) into the
adaptive-icon vector layers and the notification glyph. Dev tool: needs `pip install pillow potracer`.

The PNG is the visible 72 dp of a 108 dp adaptive-icon layer, so it maps to dp 18..90; the body,
which runs off the bottom edge, is extended to the layer's edge so masks and parallax never show a
cut. Writes res/drawable/ic_launcher_{foreground,monochrome}.xml and
media3_notification_small_icon.xml.
"""
import pathlib
import sys

import potrace
from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / "docs/design/icon/amsel-icon.png"
RES = ROOT / "app/src/main/res"
INK, AMBER, CREAM = (0x13, 0x12, 0x11), (0xF0, 0xA0, 0x30), (0xF1, 0xE9, 0xDA)
# The artwork's amber marks the beak and the eye; the icon wears moss there (owner). The beak is a
# step lighter than the day's moss, which reads as black beside the bird at icon size; the eye, on
# the black head, is the night's.
BEAK, EYE = (0x6B, 0x8E, 0x4E), (0xA3, 0xB4, 0x86)
SCALE = 72 / 1024
OFFSET = 18
# The beak is the amber above this line; the eye ring the amber below it.
BEAK_LINE = 0.47
# The one-colour glyphs show at 24 dp and less, where the eye's thin ring closes up: there the eye is
# a single round hole, this much wider than the ring, about 2.5 dp across in the status bar.
GLYPH_EYE = 1.45
# The notification glyph frames the bird so it fills the 24 dp square.
NOTIFICATION_FRAME = {"pivotX": 54, "pivotY": 54, "scaleX": 1.85, "scaleY": 1.85, "translateX": 7, "translateY": -4}


def near(c, target, tol=60):
    return sum(abs(a - b) for a, b in zip(c, target)) < tol


def trace(mask_fn, im):
    w, h = im.size
    px = im.load()
    # potracer fills where the bitmap is false, so pass the inverse of the shape.
    bitmap = potrace.Bitmap([[not mask_fn(px[x, y], x, y) for x in range(w)] for y in range(h)])
    return bitmap.trace(turdsize=8, alphamax=1.0, opticurve=True, opttolerance=0.2)


def p(pt):
    return f"{pt.x * SCALE + OFFSET:.2f},{pt.y * SCALE + OFFSET:.2f}"


def path_data(paths):
    out = []
    for curve in paths:
        out.append(f"M{p(curve.start_point)}")
        for seg in curve.segments:
            if seg.is_corner:
                out.append(f"L{p(seg.c)} L{p(seg.end_point)}")
            else:
                out.append(f"C{p(seg.c1)} {p(seg.c2)} {p(seg.end_point)}")
        out.append("Z")
    return " ".join(out)


def body_extension(im):
    """A trapezoid continuing the body's sides from the image's bottom edge to the layer's edge."""
    w, h = im.size
    px = im.load()

    def span(y):
        xs = [x for x in range(w) if near(px[x, y], INK)]
        return min(xs), max(xs)

    (l0, r0), (l1, r1) = span(h - 120), span(h - 1)
    dl, dr = (l1 - l0) / 119, (r1 - r0) / 119
    extra = 18 / SCALE + 4  # down to y = 108 dp, a little past it
    bottom = h - 1 + extra
    pts = [(l1 + 2, h - 6), (r1 - 2, h - 6), (r1 + dr * extra, bottom), (l1 + dl * extra, bottom)]
    return "M" + " L".join(f"{x * SCALE + OFFSET:.2f},{y * SCALE + OFFSET:.2f}" for x, y in pts) + " Z"


def vector(paths_xml):
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by scripts/design/trace-icon.py from docs/design/icon/amsel-icon.png (the owner's artwork). -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="108dp"\n    android:height="108dp"\n'
        '    android:viewportWidth="108"\n    android:viewportHeight="108">\n'
        f"{paths_xml}</vector>\n"
    )


def eye(im):
    """The centre and outer radius of the eye ring, in image pixels."""
    w, h = im.size
    px = im.load()
    ring = [(x, y) for y in range(int(h * BEAK_LINE), h) for x in range(w) if near(px[x, y], AMBER)]
    cx = sum(x for x, _ in ring) / len(ring)
    cy = sum(y for _, y in ring) / len(ring)
    return cx, cy, max(((x - cx) ** 2 + (y - cy) ** 2) ** 0.5 for x, y in ring)


def glyph_xml(paths_xml):
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by scripts/design/trace-icon.py. The media notification and status-bar icon: the\n"
        "     app icon's blackbird as a one-colour glyph. It overrides Media3's default icon of the same\n"
        "     name, which Media3 reads, so no code of ours does. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    xmlns:tools="http://schemas.android.com/tools"\n'
        '    tools:ignore="UnusedResources"\n'
        '    android:width="24dp"\n    android:height="24dp"\n'
        '    android:viewportWidth="108"\n    android:viewportHeight="108">\n'
        "    <group\n"
        + "\n".join(f'        android:{name}="{value}"' for name, value in NOTIFICATION_FRAME.items())
        + ">\n"
        + "".join("    " + line + "\n" for line in paths_xml.splitlines())
        + "    </group>\n</vector>\n"
    )


def path_xml(color, data):
    return (f'    <path\n        android:fillColor="#FF{color[0]:02X}{color[1]:02X}{color[2]:02X}"\n'
            f'        android:fillType="evenOdd"\n        android:pathData="{data}" />\n')


def main() -> int:
    im = Image.open(SRC).convert("RGB")
    h = im.size[1]
    ink = trace(lambda c, x, y: near(c, INK), im)
    beak = trace(lambda c, x, y: near(c, AMBER) and y < h * BEAK_LINE, im)
    ring = trace(lambda c, x, y: near(c, AMBER) and y >= h * BEAK_LINE, im)
    ext = body_extension(im)
    # One colour: bird and beak solid, the eye a round hole.
    cx, cy, r = eye(im)
    hole = (r * GLYPH_EYE) ** 2

    def solid(c, x, y):
        return (near(c, INK) or (near(c, AMBER) and y < h * BEAK_LINE)) and (x - cx) ** 2 + (y - cy) ** 2 > hole

    mono = path_data(trace(solid, im))
    (RES / "drawable/ic_launcher_foreground.xml").write_text(
        vector(path_xml(BEAK, path_data(beak)) + path_xml(EYE, path_data(ring)) + path_xml(INK, path_data(ink))
               + path_xml(INK, ext)))
    (RES / "drawable/ic_launcher_monochrome.xml").write_text(
        vector(path_xml((0, 0, 0), mono) + path_xml((0, 0, 0), ext)))
    (RES / "drawable/media3_notification_small_icon.xml").write_text(
        glyph_xml(path_xml((0xFF, 0xFF, 0xFF), mono) + path_xml((0xFF, 0xFF, 0xFF), ext)))
    print("wrote foreground, monochrome and notification icons")
    return 0


if __name__ == "__main__":
    sys.exit(main())
